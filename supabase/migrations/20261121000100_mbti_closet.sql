CREATE TABLE private_files (
    file_id TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    state TEXT NOT NULL CHECK (state IN ('uploading', 'ready', 'deleting')),
    cleanup_attempts INTEGER NOT NULL DEFAULT 0,
    state_changed_at BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE planner_previews (
    user_id BIGINT NOT NULL,
    option_id BIGINT NOT NULL,
    selection TEXT NOT NULL,
    file_id TEXT NOT NULL UNIQUE,
    PRIMARY KEY (user_id, option_id, selection),
    FOREIGN KEY (user_id, option_id) REFERENCES outfit_options(user_id, id) ON DELETE CASCADE
);

-- Keep private files referenced by inactive garments and historical outfits.
CREATE VIEW private_file_references AS
    SELECT user_id, face_photo_file_id AS file_id FROM profiles WHERE face_photo_file_id IS NOT NULL
    UNION ALL
    SELECT user_id, image_file_id FROM wardrobe_items
    UNION ALL
    SELECT user_id, preview_file_id FROM outfit_options WHERE preview_file_id IS NOT NULL
    UNION ALL
    SELECT user_id, image_file_id_snapshot FROM outfit_option_items WHERE image_file_id_snapshot IS NOT NULL
    UNION ALL
    SELECT user_id, image_file_id_snapshot FROM saved_look_items WHERE image_file_id_snapshot IS NOT NULL
    UNION ALL
    SELECT user_id, file_id FROM planner_previews;

CREATE INDEX private_files_pending_cleanup ON private_files(user_id, cleanup_attempts, file_id)
    WHERE state = 'deleting';
CREATE INDEX private_files_expiry ON private_files(user_id, state_changed_at, file_id)
    WHERE state IN ('ready', 'uploading');
CREATE INDEX profiles_by_file ON profiles(face_photo_file_id);
CREATE INDEX wardrobe_items_by_file ON wardrobe_items(image_file_id);
CREATE INDEX outfit_options_by_file ON outfit_options(preview_file_id);
CREATE INDEX outfit_option_items_snapshot_files ON outfit_option_items(image_file_id_snapshot)
    WHERE image_file_id_snapshot IS NOT NULL;
CREATE INDEX saved_look_items_snapshot_files ON saved_look_items(image_file_id_snapshot)
    WHERE image_file_id_snapshot IS NOT NULL;

-- Serialize attachment with cleanup on the registry row. PostgreSQL permits
-- concurrent writers, so the registry needs a lock even though D1 does not.
CREATE FUNCTION check_private_file_attachment() RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = app, pg_catalog
AS $$
DECLARE
    new_file TEXT := to_jsonb(NEW) ->> TG_ARGV[0];
BEGIN
    IF new_file IS NULL THEN
        RETURN NEW;
    END IF;
    IF TG_OP = 'UPDATE' AND TG_NARGS = 1
        AND OLD.user_id = NEW.user_id
        AND (to_jsonb(OLD) ->> TG_ARGV[0]) IS NOT DISTINCT FROM new_file THEN
        RETURN NEW;
    END IF;

    PERFORM 1 FROM private_files
    WHERE file_id = new_file AND user_id = NEW.user_id AND state = 'ready'
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Private file is unavailable to this account' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END
$$;

CREATE FUNCTION guard_private_file_delete_claim() RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = app, pg_catalog
AS $$
BEGIN
    -- This statement reads after the UPDATE has acquired its row lock. An
    -- attachment may have committed while the original UPDATE was waiting.
    IF NEW.state = 'deleting' AND EXISTS (
        SELECT 1 FROM private_file_references WHERE file_id = NEW.file_id
    ) THEN
        RETURN NULL;
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER private_files_guard_delete_claim
BEFORE INSERT OR UPDATE OF state ON private_files
FOR EACH ROW EXECUTE FUNCTION guard_private_file_delete_claim();

CREATE FUNCTION enqueue_detached_private_file() RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = app, pg_catalog
AS $$
DECLARE
    old_file TEXT := to_jsonb(OLD) ->> TG_ARGV[0];
BEGIN
    IF old_file IS NULL OR (
        TG_OP = 'UPDATE' AND (to_jsonb(NEW) ->> TG_ARGV[0]) IS NOT DISTINCT FROM old_file
    ) THEN
        RETURN NULL;
    END IF;

    PERFORM 1 FROM private_files WHERE file_id = old_file AND user_id = OLD.user_id FOR UPDATE;
    IF EXISTS (SELECT 1 FROM private_file_references WHERE file_id = old_file) THEN
        RETURN NULL;
    END IF;
    IF TG_NARGS > 1 THEN
        -- Planner previews always have a registry row. Legacy references in
        -- the other tables may have been created before the registry existed.
        UPDATE private_files SET state = 'deleting' WHERE file_id = old_file AND user_id = OLD.user_id;
    ELSE
        INSERT INTO private_files (file_id, user_id, state) VALUES (old_file, OLD.user_id, 'deleting')
        ON CONFLICT (file_id) DO UPDATE SET state = 'deleting'
        WHERE private_files.user_id = excluded.user_id;
    END IF;
    RETURN NULL;
END
$$;

CREATE TRIGGER profiles_check_private_file
BEFORE INSERT OR UPDATE OF user_id, face_photo_file_id ON profiles
