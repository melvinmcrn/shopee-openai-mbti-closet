CREATE FUNCTION check_garment_snapshot() RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = app, pg_catalog
AS $$
BEGIN
    IF NEW.category_snapshot IS NOT NULL THEN
        -- A competing wardrobe edit must wait until the snapshot is visible.
        PERFORM 1 FROM wardrobe_items
        WHERE user_id = NEW.user_id AND id = NEW.item_id
          AND confirmed_at IS NOT NULL AND archived_at IS NULL
          AND category = NEW.slot AND category = NEW.category_snapshot
          AND image_file_id = NEW.image_file_id_snapshot
        FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Selected garment changed. Refresh your wardrobe.' USING ERRCODE = '23514';
        END IF;
    END IF;
    IF NEW.image_file_id_snapshot IS NOT NULL THEN
        PERFORM 1 FROM private_files WHERE file_id = NEW.image_file_id_snapshot FOR UPDATE;
    END IF;
    RETURN NEW;
END
$$;

