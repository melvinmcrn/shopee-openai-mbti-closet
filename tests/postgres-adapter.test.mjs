test("Postgres preserves Worker query results and transaction boundaries", { skip: !url }, async () => {
  const sql = postgres(url, { prepare: false });
  const db = createPostgresDatabase(sql);
  const table = "adapter_test_" + crypto.randomUUID().replaceAll("-", "");

  try {
    await sql.unsafe(`CREATE TABLE app.${table} (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text UNIQUE)`);
    assert.deepEqual(await db.prepare("SELECT CAST(?2 AS text) AS mixedCase, CAST(?1 AS text) AS earlier, '?' AS literal, CAST(?2 AS text) AS repeated, 5000000000000::bigint AS bigId")
      .bind("first", "second").first(), {
      mixedCase: "second", earlier: "first", literal: "?", repeated: "second", bigId: 5000000000000,
    });
    assert.equal(await db.prepare("SELECT 'unixepoch(), last_insert_rowid()' AS value /* changes(), ? */").first("value"),
      "unixepoch(), last_insert_rowid()");
    const hostileName = "x'); DROP TABLE users; --";
    const [inserted, child] = await db.batch([
      db.prepare(`INSERT INTO ${table} (name) VALUES (?) RETURNING id, name`).bind(hostileName),
      db.prepare("SELECT last_insert_rowid() AS parentId WHERE changes() = 1"),
    ]);
    assert.equal(inserted.meta.changes, 1);
    assert.equal(child.results[0].parentId, inserted.results[0].id);
    assert.equal(inserted.results[0].name, hostileName);

    await assert.rejects(db.batch([
      db.prepare(`INSERT INTO ${table} (name) VALUES (?)`).bind("must roll back"),
      db.prepare(`INSERT INTO ${table} (name) VALUES (?)`).bind(hostileName),
    ]), { code: "23505" });
    assert.equal(await db.prepare(`SELECT count(*) AS size FROM ${table}`).first("size"), 1);

    const nonexistent = await db.batch([
      db.prepare(`INSERT INTO ${table} (name) VALUES (?) ON CONFLICT DO NOTHING RETURNING id`).bind(hostileName),
      db.prepare("SELECT last_insert_rowid() AS parentId WHERE changes() = 1"),
    ]);
    assert.deepEqual(nonexistent[1].results, []);
    assert.deepEqual(await db.prepare("SELECT value FROM json_each(?)").bind('["red","blue"]').all().then(({ results }) => results), [
      { value: "red" }, { value: "blue" },
    ]);
    assert.deepEqual(await db.prepare("SELECT json_extract(slot.value, '$.id') AS id FROM json_each(?) AS slot")
      .bind('{"shoes":{"id":9}}').first(), { id: 9 });
    assert.equal(await db.prepare("SELECT json_group_array(value) AS entries FROM json_each(?)").bind("[]").first("entries"), "[]");
    assert.deepEqual(await db.prepare("SELECT CASE WHEN ? THEN 'true' ELSE 'false' END AS choice WHERE CAST(NULL AS text) IS ?")
      .bind(1, null).first(), { choice: "true" });
  } finally {
    await sql.unsafe(`DROP TABLE IF EXISTS app.${table}`);
    await sql.end();
  }
});

test("Postgres supports owner-scoped profiles, wardrobe items, and the planner", { skip: !url }, async (t) => {
  const sql = postgres(url, { prepare: false });
  const DB = createPostgresDatabase(sql);
  const accounts = [];
  const objects = new Map();
  const env = {
    readSampleImage,
    DB,
    WARDROBE_EXTRACTION_FIXTURES: "1",
    BUCKET: {
      async put(key, bytes, metadata) { objects.set(key, { blob: new Blob([bytes]), ...metadata }); },
      async get(key) {
        const file = objects.get(key);
        return file ? {
          body: file.blob.stream(), size: file.blob.size,
          arrayBuffer: () => file.blob.arrayBuffer(), httpMetadata: file.httpMetadata,
        } : null;
      },
      async delete(key) { objects.delete(key); },
    },
  };
  const createAccount = async () => {
    const account = await DB.prepare("INSERT INTO users (auth_provider, auth_subject) VALUES ('google', ?) RETURNING id")
      .bind(crypto.randomUUID()).first();
    accounts.push(account.id);
    return account;
  };

  try {
    const [owner, visitor] = await Promise.all([createAccount(), createAccount()]);
    const owned = userData(DB, owner.id);
    const other = userData(DB, visitor.id);
    await owned.saveProfile({ heightCm: 169.5, styles: ["formal", "casual"] });
    assert.deepEqual(await owned.getProfile(), {
      heightCm: 169.5, weightKg: null, facePhotoFileId: null, setupCompletedAt: null, styles: ["casual", "formal"],
    });
    const profileResponse = await profile(new Request("https://example.test/api/profile"), env, owner.id);
    assert.equal(profileResponse.status, 200);
    assert.deepEqual((await profileResponse.json()).styles, ["casual", "formal"]);
    assert.equal(await other.getProfile(), null);

    const garments = {};
    for (const category of ["top", "bottom", "shoes"]) {
      const file = await writePrivateFile(env, owner, Uint8Array.of(1, 2, 3), "image/png");
      const garment = await owned.createWardrobeItem({
        name: category, category, imageFileId: file, confirmedAt: "2026-11-21 10:00:00",
      });
      assert.equal(await other.getWardrobeItem(garment.id), null);
      assert.equal(await readPrivateFile(env, visitor, file), null);
      assert.ok(await readPrivateFile(env, owner, file));
      garments[category] = String(garment.id);
    }
    assert.equal((await owned.getActiveWardrobeItems(Object.values(garments).map(Number))).length, 3);

    const brief = await dispatchPlanner(env, owner.id, "saveBrief", {
      occasion: "Dinner", comfort: "Loosely fitted", preferences: ["shoes", "top"],
    });
    assert.ok(Number.isSafeInteger(Number(brief.id)));
    assert.deepEqual(brief.preferences, ["shoes", "top"]);
    const extra = await owned.createOutfitRequest({
      occasion: "Lunch", comfortChoices: ["Warm"], clothingChoices: [{ category: "top", garmentType: "tee" }],
    });
    assert.deepEqual(extra.comfortChoices, ["Warm"]);
    assert.deepEqual(extra.clothingChoices, [{ category: "top", garmentType: "tee" }]);

    const generated = await dispatchPlanner(env, owner.id, "generate", { briefId: brief.id }, {
      generateLooks: async () => ({ status: "ready", looks: [{ slots: garments, explanation: "A complete outfit" }] }),
    });
    const option = generated.looks[0];
    assert.deepEqual((await dispatchPlanner(env, owner.id, "option", { id: option.id })).slots, garments);
    const look = await dispatchPlanner(env, owner.id, "save", { optionId: option.id, slots: garments });
    assert.equal(look.slots.shoes.id, garments.shoes);
    assert.deepEqual(await dispatchPlanner(env, visitor.id, "list"), []);
    const wear = await dispatchPlanner(env, owner.id, "wearAdd", { lookId: look.id, date: "2026-11-21" });
    await dispatchPlanner(env, owner.id, "wearUpdate", { id: wear.id, rating: 5 });
    assert.equal((await dispatchPlanner(env, owner.id, "wearGet", { id: wear.id })).rating, 5);

    await t.test("a concurrent save invalidates an older deletion confirmation", async () => {
      const ready = Promise.withResolvers();
      const release = Promise.withResolvers();
      // Hold the real save transaction after writing the look, until the
      // deletion has acquired its snapshot on a second database connection.
      const savingDb = createPostgresDatabase({ begin: (isolation, run) => sql.begin(isolation, async (tx) => {
        const rows = await run(tx);
        ready.resolve();
        await release.promise;
        return rows;
      }) });
      const deletingDb = createPostgresDatabase({ begin: (isolation, run) => sql.begin(isolation, async (tx) => {
        await tx.unsafe("SELECT 1");
        release.resolve();
        return run(tx);
      }) });
      const remove = (db, savedLookIds) => wardrobeApi(new Request(`https://example.test/api/wardrobe/items/${garments.top}`, {
        method: "DELETE", body: JSON.stringify({ savedLookIds }),
      }), { DB: db }, owner.id);
      const wardrobe = await dispatchPlanner(env, owner.id, "wardrobe");
      const saving = saveLook(savingDb, owner.id, option, garments, wardrobe);
      try {
        await Promise.race([ready.promise, saving]);
        const response = await remove(deletingDb, [Number(look.id)]);
        const concurrent = await saving;
        assert.equal(response.status, 409);
        const savedLooks = [look, concurrent].map(({ id, occasion }) => ({ id: Number(id), title: occasion }));
        assert.deepEqual(await response.json(), { code: "saved_looks_affected", savedLooks });
        assert.equal((await remove(DB, savedLooks.map(({ id }) => id))).status, 204);
        assert.deepEqual(await dispatchPlanner(env, owner.id, "list"), []);
        await assert.rejects(saveLook(DB, owner.id, option, garments, wardrobe), /Selected garment changed/);
        const replacement = await owned.saveLook({
          sourceOptionId: Number(option.id), name: "Replacement", slots: [{ slot: "shoes", itemId: Number(garments.shoes) }],
        });
        assert.ok(replacement.id > Number(concurrent.id));
        assert.deepEqual(replacement.slots.map(({ itemId }) => itemId), [Number(garments.shoes)]);
      } finally {
        release.resolve();
        await saving;
      }
    });

    const sampleRequest = () => new Request("https://example.test/api/wardrobe/sample", { method: "POST" });
    const [initialSamples, repeatedSamples] = await Promise.all(
      [sampleRequest(), sampleRequest()].map(async (request) => (await sample(request, env, owner.id)).json()),
    );
    assert.equal(initialSamples.items.length, 7);
    assert.deepEqual(repeatedSamples, initialSamples);
    assert.equal(objects.size, 10);
    assert.deepEqual(await other.listWardrobeItems(), []);

    const original = await readFile(new URL("../src/app/api/_server/wardrobe/extraction-fixtures/shirt.png", import.meta.url));
    const originalFileId = await writePrivateFile(env, owner, original, "image/png");
    const draft = await owned.createWardrobeItem({ name: "Draft", category: "other", imageFileId: originalFileId });
    const extractRequest = () => new Request(`https://example.test/api/wardrobe/items/${draft.id}/extract`, { method: "POST" });
    assert.equal((await extract(extractRequest(), env, visitor.id, String(draft.id))).status, 404);
    const extracted = await extract(extractRequest(), env, owner.id, String(draft.id));
    assert.equal(extracted.status, 200);
    const cutout = (await extracted.json()).item;
    assert.equal(cutout.category, "top");
    assert.ok(cutout.imageFileId !== originalFileId);
    assert.ok(objects.has(cutout.imageFileId));
    assert.equal(objects.has(originalFileId), false);
  } finally {
    try {
      for (const id of accounts) {
        await DB.batch([
          DB.prepare("DELETE FROM outfit_requests WHERE user_id = ?").bind(id),
          DB.prepare("DELETE FROM users WHERE id = ?").bind(id),
          DB.prepare("DELETE FROM private_files WHERE user_id = ?").bind(id),
        ]);
      }
    } finally {
      await sql.end();
    }
  }
});
